import fs from 'node:fs/promises';
import path from 'node:path';
import {build} from 'vite';
const root=process.cwd();
await build();
const assets={};
const types={'.html':'text/html; charset=utf-8','.css':'text/css; charset=utf-8','.js':'text/javascript; charset=utf-8','.json':'application/json','.svg':'image/svg+xml','.png':'image/png','.woff2':'font/woff2'};
async function collect(directory,prefix=''){
  for(const entry of await fs.readdir(directory,{withFileTypes:true})){
    const relative=prefix+'/'+entry.name,file=path.join(directory,entry.name);
    if(entry.isDirectory()){await collect(file,relative);continue;}
    const ext=path.extname(file),data=await fs.readFile(file),binary=['.png','.jpg','.webp','.woff2'].includes(ext);
    assets[relative]={body:data.toString(binary?'base64':'utf8'),type:types[ext]||'application/octet-stream',binary};
  }
}
await collect(path.join(root,'dist/client'));
await fs.mkdir(path.join(root,'worker'),{recursive:true});
await fs.writeFile(path.join(root,'worker/assets.generated.mjs'),'// Generated by scripts/build-assets.mjs\nexport const ASSETS='+JSON.stringify(assets)+';\n');
console.log('Packed Vite production assets.');
